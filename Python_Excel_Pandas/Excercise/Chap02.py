#2.1.6 리스트
print([1, 2, 3] + [4, 5]) #리스트를 더하면 리스트가 연결된다. #결과는 [1, 2, 3, 4, 5]가 나온다.
print([1, 2, 3] * 2) #리스트를 곱하면 리스트가 반복된다. #결과는 [1, 2, 3, 1, 2, 3]이 나온다.
b = [1, 2, 3]
print(b[0]) #리스트의 첫 번째 요소를 출력한다. #결과는 1이 나온다.
print(len(b)) #리스트의 길이를 출력한다. #결과는 3이 나온다.

#2.1.7 튜플
(1, 2, 3) #튜플은 리스트와 비슷하지만, 요소를 변경할 수 없다. #튜플은 소괄호로 감싸서 만든다.
print((1, 2, 3) + (4, 5)) #튜플을 더하면 튜플이 연결된다. #결과는 (1, 2, 3, 4, 5)가 나온다.
print(type((1, 2, 3))) #튜플의 타입을 출력한다. #결과는 <class 'tuple'>이 나온다.
c = 1, 2
print(type(c)) #튜플의 타입을 출력한다. #결과는 <class 'tuple'>이 나온다. #튜플은 소괄호로 감싸지 않아도 된다. #하지만 가독성을 위해서 소괄호로 감싸는 것이 좋다.
d, e = 1, 2 #튜플을 이용해서 여러 개의 변수를 한 번에 할당할 수 있다. #d에는 1이, e에는 2가 할당된다.
print(d) #d의 값을 출력한다. #결과는 1이 나온다.
print(e) #e의 값을 출력한다. #결과는 2가 나온다.

