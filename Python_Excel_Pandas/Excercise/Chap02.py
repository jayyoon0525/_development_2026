#2.1.4 문자열 다루기
print('김' + '판다')
a = '김판다'
print(a[0])
print(len(a))
a = '김판다'
b = '판다스'
f'{a}강사와 함께 {b}를 배웁시다.' #이건 일반 python에서는 출력이 안되고 jupyter notebook에서만 출력이 된다.
print(f'{a}강사와 함께 {b}를 배웁시다.') #이 줄이 일반 python에서 출력 된다.
print("{}강사와 함께 {}를 배움시다.".format(a, b)) #이 줄도 일반 python에서 출력된다. #8번과 같은 결과가 나온다. #format은 {}안에 순서대로 a, b가 들어간다..
print(a + '강사와 함께 ' + b + '를 배웁시다.') #이 줄도 일반 python에서 출력된다. #8번과 같은 결과가 나온다. #문자열을 더해서 연결하는 방법이다. #하지만 이 방법은 가독성이 떨어진다. #그래서 f-string이나 format을 사용하는 것이 좋다.

